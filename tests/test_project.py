"""New-layout checks: no NPU, camera, JTAG, CARLA actors or running-app control."""
from pathlib import Path
import hashlib
import importlib.util
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
import unittest
from unittest.mock import patch,Mock

ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'scripts'))
import runtime_layout as runtime
import project as launcher


class Tests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.temp_parent=(ROOT.parent/'analysis/submission2_validation_20261031').resolve()
        cls.temp_parent.mkdir(parents=True,exist_ok=True)
        cls.work=Path(tempfile.mkdtemp(prefix='layout ',dir=cls.temp_parent)).resolve()
        assert cls.work.is_relative_to(cls.temp_parent)
        cls.before=os.environ.get('FPGA_ADAS_RUNTIME_DIR')
        os.environ['FPGA_ADAS_RUNTIME_DIR']=str(cls.work/'runtime')

    @classmethod
    def tearDownClass(cls):
        if cls.before is None:os.environ.pop('FPGA_ADAS_RUNTIME_DIR',None)
        else:os.environ['FPGA_ADAS_RUNTIME_DIR']=cls.before
        assert cls.work.resolve().is_relative_to(cls.temp_parent.resolve()) and cls.work!=cls.temp_parent
        shutil.rmtree(cls.work)

    def test_classified_files_match_original_hashes(self):
        data=json.loads((ROOT/'verification/source_mapping.json').read_text(encoding='utf-8'))
        for row in data['files']:
            self.assertEqual(hashlib.sha256((ROOT/row['new']).read_bytes()).hexdigest(),row['sha256'],row['new'])

    def test_models_and_video_have_single_source_copy(self):
        for filename in ('A_rk3568_int8.rknn','R15_256x448_patched_native_int8.rknn','video_20260929_112507.mp4'):
            found=[p for p in ROOT.rglob(filename) if '.runtime' not in p.relative_to(ROOT).parts]
            self.assertEqual(len(found),1,(filename,found))
        self.assertEqual((ROOT/'models/object_detection/classes.txt').read_text(encoding='utf-8').splitlines()[-1],'crosswalk')

    def test_four_RK_layouts_preserve_all_mapped_bytes_and_entries(self):
        entries={'decision':'launch_decision.py','four_camera':'launch_cameras.py','offline':'launch_offline.py'}
        for profile in runtime.PROFILES:
            module=runtime.materialize('rk3568_'+profile)
            for relative,item in runtime.layout('rk3568_'+profile).items():
                self.assertEqual(runtime.digest(module/relative),item['sha256'])
            checked=subprocess.run([sys.executable,'-B',str(module/'Verification/verify_submission.py'),'--section','board'],capture_output=True,text=True)
            self.assertEqual(checked.returncode,0,checked.stdout+checked.stderr)
            if profile in entries:
                result=subprocess.run([sys.executable,'-I','-B',str(module/'Board_RK3568'/entries[profile]),'--check'],capture_output=True,text=True)
                self.assertEqual(result.returncode,0,result.stdout+result.stderr)
        self.assertIn('>= .30',(runtime.materialize('rk3568_carla_navigation')/'Board_RK3568/run_carla_aeb.py').read_text())
        policy=json.loads((ROOT/'configs/profiles/four_camera.json').read_text())
        self.assertEqual(policy['class10_min_confidence'],.4)

    def test_three_PC_profiles_import_without_starting_a_window(self):
        for profile in ('decision','four_camera','carla_navigation'):
            result=subprocess.run([sys.executable,'-I','-B',str(ROOT/'software/pc/launch_console.py'),'--profile',profile,'--check'],capture_output=True,text=True,encoding='utf-8',errors='replace')
            self.assertEqual(result.returncode,0,result.stdout+result.stderr)
            info=json.loads(result.stdout)
            self.assertEqual(info['PC_panel_version'],'stereo_console.v0.1.5')
            self.assertEqual(info['default_source'],'carla' if profile=='carla_navigation' else 'pcie')
            for path in info['module_paths'].values():
                self.assertTrue(Path(path).resolve().is_relative_to(self.work.resolve()))

    def test_all_PDS_source_references_close_in_generated_layout(self):
        for profile in ('decision','four_camera','rear_camera'):
            project=runtime.materialize('hardware_'+profile)
            files=list(project.glob('*.pds'))
            self.assertTrue(files,profile)
            refs=[]
            for pds in files:
                refs+=re.findall(r'\(_file "([^"]+)"',pds.read_text(encoding='utf-8'))
            self.assertTrue(refs,profile)
            for name in refs:
                # Original PDS also records prior generated output locations.
                # They are regenerated by PDS, not source inputs to archive.
                if Path(name).parts[0] in ('compile','device_map','generate_bitstream','generate_netlist','place_route','report_power','report_timing','synthesize'):
                    continue
                p=(project/name).resolve()
                self.assertTrue(p.is_relative_to(project.resolve()),name)
                self.assertTrue(p.is_file(),str(p))

    def test_original_final_submission_remained_unchanged(self):
        original=ROOT.parent/'Final submission'
        if not original.is_dir():self.skipTest('Independent new checkout; original archive not present')
        data=json.loads((ROOT/'verification/source_snapshot.json').read_text(encoding='utf-8'))
        for row in data['files']:
            p=original/row['path']
            self.assertTrue(p.is_file(),row['path'])
            self.assertEqual(runtime.digest(p),row['sha256'],row['path'])

    def test_layout_rejects_path_escape_and_modified_runtime(self):
        with self.assertRaises(ValueError):runtime.inside(self.work,'../outside')
        target=runtime.materialize('rk3568_offline')
        p=target/'Board_RK3568/Configuration/offline_defaults.json'
        original=p.read_bytes()
        try:
            p.write_text('{}',encoding='utf-8')
            with self.assertRaises(RuntimeError):runtime.materialize('rk3568_offline')
        finally:p.write_bytes(original)

    def test_engine_launcher_reuses_existing_instance_and_keeps_rendering_flags(self):
        engine=self.work/'engine';engine.mkdir(exist_ok=True)
        (engine/'CarlaUE4.exe').write_bytes(b'test placeholder, never executed')
        with patch.object(launcher,'settings',return_value={'carla_root':str(engine)}), \
             patch.object(launcher.platform,'system',return_value='Windows'), \
             patch.object(launcher.subprocess,'check_output',return_value='"CarlaUE4.exe","42"') as tasks, \
             patch.object(launcher.subprocess,'Popen') as start:
            launcher.start_carla();start.assert_not_called()
            self.assertIn('CSV',tasks.call_args.args[0])
        with patch.object(launcher,'settings',return_value={'carla_root':str(engine)}), \
             patch.object(launcher.platform,'system',return_value='Windows'), \
             patch.object(launcher.subprocess,'check_output',return_value=''), \
             patch.object(launcher.subprocess,'Popen') as start:
            launcher.start_carla()
            self.assertEqual(start.call_args.args[0][1:],['-quality-level=Low','-RenderOffScreen','-fps=20'])

    def test_console_launcher_refuses_an_occupied_diagnostic_port(self):
        probe=Mock();probe.connect_ex.return_value=0
        with patch.object(launcher.platform,'system',return_value='Windows'), \
             patch.object(launcher.socket,'socket',return_value=probe), \
             patch.object(launcher.subprocess,'Popen') as start:
            with self.assertRaises(SystemExit):launcher.run_pc('decision')
            start.assert_not_called();probe.close.assert_called_once()


if __name__=='__main__':unittest.main(verbosity=2)
